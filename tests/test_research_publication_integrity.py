"""Integrity checks for the public ``research/`` evidence tree.

Guards review warp-drive-38 @ a084a6e0 BLOCKING 1: the eight evidence files
listed in ``research/PUBLICATION_GAPS.md`` "Still missing" are intentionally
excluded from this public copy and cannot be regenerated byte-for-byte, so no
manifest or public text may claim they are present, and no public text may
state the ratchet-001 receipt-log SHA-256, terminal receipt SHA-256, or
``chain_valid`` as re-verified here while ``receipts.jsonl`` is absent.

Stdlib only; no network. ``research/`` itself is collect-ignored by
``research/conftest.py``, so this file lives in the main suite.
"""

from __future__ import annotations

import hashlib
import re
import unittest
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
RESEARCH = REPO_ROOT / "research"
GAPS_MD = RESEARCH / "PUBLICATION_GAPS.md"
RATCHET = RESEARCH / "ratchet-001"
RESULT_MD = RATCHET / "RESULT.md"
REDACTIONS_MD = RATCHET / "PUBLICATION_REDACTIONS.md"
RECEIPTS_JSONL = RATCHET / "runs" / "001-baseline" / "receipts.jsonl"
PR15 = RESEARCH / "reviews" / "2026-11-22" / "pr15-final"

LABEL = "cannot be re-verified here"
RECEIPT_LOG_SHA256 = "e33481b234e8ddf706cb477c77dd54c79e7dbeb829b4ae104d603228a3e46dcb"
TERMINAL_RECEIPT_SHA256 = "4f046fbfc2f9a1855c15226d762a09e831e4ab86ea758e2cd0b6a5871078391f"
CHAIN_VALID = '{"chain_valid":true}'
MISSING_PR15_LOGS = (
    "independent-witnesses.harness-initial.log",
    "independent-witnesses.log",
    "legacy-constructor-types.log",
    "test-normal.log",
    "test-optimized.log",
    "test_warp_drive_runtime_r5.py.log",
    "test_weft_cross_audit_r5.py.log",
)
# Author-local paths recorded only in pr20-rereview/SHA256SUMS.local-original
# (the local git dir was never part of the public copy).
LOCAL_ONLY_PREFIX = "reviews/2026-11-22/pr20-rereview/repo.git/"


def sha256_file(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def parse_manifest(path: Path) -> dict[str, str]:
    """Parse a sha256sum-style manifest into {name relative to its dir: digest}."""
    entries: dict[str, str] = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line:
            continue
        digest, name = line.split(None, 1)
        name = name.strip()
        while name.startswith("./"):
            name = name[2:]
        entries[name] = digest
    return entries


def _section(text: str, header_prefix: str) -> str:
    match = re.search(rf"^## {re.escape(header_prefix)}.*$", text, re.MULTILINE)
    if match is None:
        return ""
    rest = text[match.start():]
    nxt = re.search(r"^## ", rest[1:], re.MULTILINE)
    return rest[: nxt.start() + 1] if nxt else rest


def _table_rows(section: str) -> list[list[str | None]]:
    """Rows of a markdown table; each cell is its first backticked token or None."""
    rows: list[list[str | None]] = []
    for line in section.splitlines():
        if not line.startswith("|"):
            continue
        cells = [cell.strip() for cell in line.split("|")[1:-1]]
        tokens = []
        for cell in cells:
            m = re.search(r"`([^`]+)`", cell)
            tokens.append(m.group(1) if m else None)
        if tokens and tokens[0] is not None:
            rows.append(tokens)
    return rows


def parse_still_missing(gaps_text: str) -> dict[str, str]:
    """research-relative path -> recorded digest from the 'Still missing' table."""
    section = _section(gaps_text, "Still missing")
    missing: dict[str, str] = {}
    for row in _table_rows(section):
        if len(row) >= 2 and row[1] is not None:
            missing[row[0]] = row[1]
    return missing


def parse_changed(gaps_text: str) -> dict[str, tuple[str | None, str]]:
    """research-relative path -> (recorded digest or None, current digest)."""
    section = _section(gaps_text, "Changed by this fix")
    changed: dict[str, tuple[str | None, str]] = {}
    for row in _table_rows(section):
        if len(row) >= 3 and row[2] is not None:
            changed[row[0]] = (row[1], row[2])
    return changed


class ResearchPublicationIntegrityTest(unittest.TestCase):
    """Every check fails on the unfixed tree (review a084a6e0)."""

    @classmethod
    def setUpClass(cls) -> None:
        cls.gaps_text = GAPS_MD.read_text(encoding="utf-8")
        cls.still_missing = parse_still_missing(cls.gaps_text)
        cls.changed = parse_changed(cls.gaps_text)
        cls.manifests = sorted(p for p in RESEARCH.rglob("SHA256SUMS*") if p.is_file())

    def test_manifests_match_present_files_or_documented_gaps(self) -> None:
        # The gaps file must document this fix and its labelled edits.
        self.assertIn("## Changed by this fix", self.gaps_text)
        self.assertIn("SHA256SUMS.local-original", self.gaps_text)
        self.assertIn("repo.git", self.gaps_text)
        for rel in (
            "ratchet-001/RESULT.md",
            "ratchet-001/PUBLICATION_REDACTIONS.md",
            "reviews/2026-11-22/pr15-final/PUBLICATION.md",
            "reviews/2026-11-22/pr15-final/SHA256SUMS.public",
        ):
            self.assertIn(rel, self.changed, f"{rel} not documented in PUBLICATION_GAPS.md")
        # The "Still missing" inventory must be present and non-empty.
        self.assertEqual(len(self.still_missing), 8)
        # Every Still missing entry must indeed be absent from this copy.
        for rel in self.still_missing:
            self.assertFalse((RESEARCH / rel).exists(), f"{rel} exists but is listed as missing")

        problems: list[str] = []
        for manifest in self.manifests:
            for name, digest in parse_manifest(manifest).items():
                path = manifest.parent / name
                rel = path.relative_to(RESEARCH).as_posix()
                if rel in self.still_missing:
                    if path.exists():
                        problems.append(f"{manifest.name}: {name} exists but is 'Still missing'")
                    elif digest != self.still_missing[rel]:
                        problems.append(
                            f"{manifest.name}: {name} digest {digest} != gaps record {self.still_missing[rel]}"
                        )
                    continue
                if path.exists():
                    actual = sha256_file(path)
                    if actual == digest:
                        continue
                    if rel in self.changed:
                        recorded, current = self.changed[rel]
                        if actual == current and (recorded is None or recorded == digest):
                            continue  # labelled edit; recorded value kept in the manifest
                    if manifest.name.endswith(".local-original"):
                        continue  # recorded local manifest: pre-redaction hashes by design
                    problems.append(
                        f"{manifest.name}: {name} hashes {actual}, manifest records {digest}"
                    )
                elif manifest.name.endswith(".local-original") and rel.startswith(LOCAL_ONLY_PREFIX):
                    continue  # author-local repo.git tree, documented in PUBLICATION_GAPS.md
                else:
                    problems.append(
                        f"{manifest.name}: {name} is absent and not listed in PUBLICATION_GAPS.md 'Still missing'"
                    )
        self.assertEqual(problems, [])

        # Recorded digests for the labelled edits must remain visible (not altered)
        # in the recorded manifests / redaction receipt.
        recorded_text = "\n".join(
            p.read_text(encoding="utf-8")
            for p in [*RESEARCH.rglob("SHA256SUMS*"), REDACTIONS_MD]
            if p.is_file()
        )
        for rel, (recorded, _current) in self.changed.items():
            if recorded is not None:
                self.assertIn(recorded, recorded_text, f"recorded digest for {rel} no longer visible")

    def test_pr15_public_manifest_verifies_and_covers_present_files(self) -> None:
        public = PR15 / "SHA256SUMS.public"
        self.assertTrue(public.is_file(), "pr15-final/SHA256SUMS.public is missing")
        entries = parse_manifest(public)
        self.assertTrue(entries)
        for name, digest in entries.items():
            path = PR15 / name
            self.assertTrue(path.is_file(), f"SHA256SUMS.public lists absent {name}")
            self.assertEqual(sha256_file(path), digest, f"SHA256SUMS.public digest mismatch for {name}")
        present = {p.name for p in PR15.iterdir() if p.is_file() and p.name != "SHA256SUMS.public"}
        self.assertEqual(set(entries), present, "SHA256SUMS.public must list every present file")
        # Entries shared with the recorded SHA256SUMS carry the same hash, except
        # the files this fix deliberately re-labelled (documented in the gaps file).
        full = parse_manifest(PR15 / "SHA256SUMS")
        labelled = {rel.rsplit("/", 1)[-1] for rel in self.changed if rel.startswith("reviews/2026-11-22/pr15-final/")}
        for name, digest in entries.items():
            if name in full and name not in labelled:
                self.assertEqual(full[name], digest, f"{name}: SHA256SUMS.public vs SHA256SUMS hash differ")

    def test_result_md_labels_receipt_claims_while_log_absent(self) -> None:
        text = RESULT_MD.read_text(encoding="utf-8")
        if not RECEIPTS_JSONL.exists():
            for marker in (RECEIPT_LOG_SHA256, TERMINAL_RECEIPT_SHA256, CHAIN_VALID):
                lines = [line for line in text.splitlines() if marker in line]
                self.assertTrue(lines, f"{marker} not stated in RESULT.md")
                for line in lines:
                    self.assertIn(LABEL, line, f"unlabelled receipt claim in RESULT.md: {line}")
            self.assertIn("cannot run on this copy", text)
            self.assertIn("FileNotFoundError", text)
        redactions = REDACTIONS_MD.read_text(encoding="utf-8")
        if not RECEIPTS_JSONL.exists():
            for line in redactions.splitlines():
                if TERMINAL_RECEIPT_SHA256 in line:
                    self.assertIn(LABEL, line, f"unlabelled terminal receipt claim: {line}")

    def test_publication_text_no_false_coverage_or_presence_claims(self) -> None:
        for pub_md in sorted(RESEARCH.rglob("PUBLICATION.md")):
            sums = pub_md.parent / "SHA256SUMS"
            if not sums.is_file():
                continue
            missing = [name for name in parse_manifest(sums) if not (pub_md.parent / name).exists()]
            text = pub_md.read_text(encoding="utf-8")
            if missing:
                self.assertNotIn("covers every file", text, str(pub_md))
                self.assertIn("PUBLICATION_GAPS.md", text, str(pub_md))
        pr15_publication = (PR15 / "PUBLICATION.md").read_text(encoding="utf-8")
        self.assertIn("SHA256SUMS.public", pr15_publication)
        self.assertIn("not in this public copy", pr15_publication)
        for log in MISSING_PR15_LOGS:
            self.assertIn(log, pr15_publication, f"{log} not named in pr15 PUBLICATION.md")
        # The review report itself stays byte-identical to its recorded hash.
        report_sha = hashlib.sha256((PR15 / "REPORT.md").read_bytes()).hexdigest()
        self.assertEqual(report_sha, "4aae8a6ba1400c39ab9beb484a4dcebe50097356c9b026793fdc99a735fc10f8")


if __name__ == "__main__":
    unittest.main()
